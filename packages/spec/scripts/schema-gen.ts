import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as S from "../src/index";
import { SCHEMAS, renderAll, suiteWidgets } from "./schemas";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..", "generated");
mkdirSync(out, { recursive: true });
for (const [file, text] of Object.entries(renderAll())) writeFileSync(join(out, file), text);
console.log(`wrote ${Object.keys(SCHEMAS).length} schemas to ${out}`);

// The web client has no build step: give it the widget catalogue as a plain ES module (generated, never hand-edited).
const NL = String.fromCharCode(10);
const web = join(here, "..", "..", "web", "src", "core", "widget-schemas.js");
mkdirSync(dirname(web), { recursive: true });
writeFileSync(
  web,
  "// Generated by `pnpm schema:gen` from @plinth/spec WIDGET_CATALOGUE. Do not edit." +
    NL +
    "export const WIDGET_CATALOGUE = " +
    suiteWidgets().trimEnd() +
    ";" +
    NL,
);
console.log(`wrote ${web}`);

// Route table for the web client's api.call(actionName, input): name -> { method, path, mutating }.
const routes = join(here, "..", "..", "web", "src", "core", "action-routes.js");
writeFileSync(
  routes,
  "// Generated by `pnpm schema:gen` from @plinth/spec ACTIONS. Do not edit." +
    NL +
    "export const ACTION_ROUTES = " +
    JSON.stringify(
      Object.fromEntries(S.ACTIONS.map((a) => [a.name, { method: a.method, path: a.path, mutating: a.mutating }])),
      null,
      2,
    ) +
    ";" +
    NL,
);
console.log(`wrote ${routes}`);
