/**
 * The Suite action registry (CONTRACT.md section 5). It is the single implementation surface: every HTTP route under
 * `/suite` is the registry entry with that method and path, `POST /suite/actions/:name` invokes any entry by name, and
 * the MCP tool `action.invoke` dispatches the same entries. A human and an agent therefore reach exactly the same
 * code, permission checks and events.
 *
 * Input decoding: path parameters (`:name` segments) and, for GET and DELETE, query-string parameters are merged into
 * one object and decoded with `input`; for POST and PUT the JSON body is merged with the path parameters. Query values
 * are coerced to the schema's number/boolean types; arrays are comma-separated (`status=placed,approved`).
 * Every success response is `{ ok: true, data: <output> }`.
 *
 * `agent` is the discipline for agent principals (spec 06 gate): `direct` runs at once (reads); `preview` needs a
 * dry run returning a preview_token, then a commit with that token and an idempotency key; `approval` is `preview`
 * whose commit is filed in action_approvals for a human; `deny` is refused with FORBIDDEN (ceiling_denies).
 */

export type AgentPolicy = "direct" | "preview" | "approval" | "deny";
export type Method = "GET" | "POST" | "PUT" | "DELETE";

export interface ActionDef {
  readonly name: string;
  readonly module: SuiteModule;
  readonly method: Method;
  readonly path: string;
  /** The permission checked on `plinth://<ws>/suite/<module>`; `authenticated` needs only a valid principal. */
  readonly permission: string;
  readonly mutating: boolean;
  readonly agent: AgentPolicy;
  readonly input: S.Schema.AnyNoContext;
  readonly output: S.Schema.AnyNoContext;
  readonly reasons: ReadonlyArray<Reason>;
  readonly events: ReadonlyArray<DomainEventType>;
  readonly summary: string;
}

const a = (d: ActionDef): ActionDef => d;
const R = <T extends ReadonlyArray<Reason>>(...r: T) => r;
const E = <T extends ReadonlyArray<DomainEventType>>(...e: T) => e;

