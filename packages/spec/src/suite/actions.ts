export const ActionCatalogEntry = S.Struct({
  name: S.String,
  module: S.String,
  method: S.String,
  path: S.String,
  permission: S.String,
  mutating: S.Boolean,
  agent: S.Literal("direct", "preview", "approval", "deny"),
  summary: S.String,
  reasons: S.Array(SuiteReason),
  events: S.Array(DomainEventTypeSchema),
  input_schema: S.optional(S.Unknown),
  output_schema: S.optional(S.Unknown),
}).annotations({ identifier: "ActionCatalogEntry" });

export const ActionsListIn = S.Struct({
  module: S.optional(S.String),
  name: S.optional(S.String),
  include_schemas: S.optional(S.Boolean),
}).annotations({ identifier: "ActionsListIn" });
export const ActionsListOut = S.Struct({ items: S.Array(ActionCatalogEntry) });

/**
 * `POST /suite/actions/:name` body, and the MCP `action.invoke` arguments (with `action`). Three forms:
 * read: `{ input }`; preview: `{ input, dry_run: true }`; commit: `{ preview_token, idempotency_key }`.
 * Humans over HTTP may also commit directly with `{ input }` (and `input.idempotency_key` where the input has one).
 */
export const ActionInvokeIn = S.Struct({
  input: S.optional(S.Record({ key: S.String, value: S.Unknown })),
  dry_run: S.optional(S.Boolean),
  preview_token: S.optional(S.String.pipe(S.pattern(/^pvt_[A-Za-z0-9_-]{43}$/))),
  idempotency_key: S.optional(IdempotencyKey),
  reason: S.optional(S.String.pipe(S.maxLength(280))),
}).annotations({ identifier: "ActionInvokeIn" });

export const ActionPreview = S.Struct({
  action: S.String,
  decision: S.Literal("auto", "approval"),
  /** Plinth-authored description of the effect, e.g. "Transfer 500 pts from maya-ortiz to ana-silva (balance 4 120 -> 3 620)". */
  effect: S.String,
  /** Typed facts behind the effect (amounts, balances after, recipients count, promotions applied). */
  facts: S.Record({ key: S.String, value: S.Unknown }),
  input_hash: S.String,
  preview_token: S.String,
  expires_in_s: S.Int,
}).annotations({ identifier: "ActionPreview" });

export const ActionInvokeOut = S.Union(
  S.Struct({ kind: S.Literal("result"), action: S.String, data: S.Unknown, replayed: S.Boolean }),
  S.Struct({ kind: S.Literal("preview"), preview: ActionPreview }),
  S.Struct({
    kind: S.Literal("pending_approval"),
    action: S.String,
    approval_id: S.UUID,
    approver_permission: S.String,
  }),
).annotations({ identifier: "ActionInvokeOut" });

export const actionByName = (name: string): ActionDef | undefined => ACTIONS.find((x) => x.name === name);
