/**
 * The widget catalogue (CONTRACT.md section 5A). Domains expose widgets; a widget is a self-contained mini-app with its
 * own state, its own data access through its domain's actions and realtime events, its own internal views, and a typed
 * configuration. Every page (home, profile, module pages, custom pages) is a Page node laying out Widget instance
 * nodes. The kernel Panel is the reporting domain's original widget and stays valid inside Pages.
 *
 * `WIDGET_CATALOGUE` is data the server serves (`GET /suite/widgets`), `schema.describe("Widget")` returns, and
 * `pnpm schema:gen` writes to `packages/spec/generated/suite.widgets.json` and `packages/web/src/core/widget-schemas.js`.
 */

// ---- shared config pieces -------------------------------------------------------------------------

/** A config value bound to a page route parameter (`/store/p/:slug` -> `{ "param": "slug" }`). */
export const ParamBinding = S.Struct({ param: S.String.pipe(S.pattern(/^[a-z][a-z_]{0,31}$/)) }).annotations({
  identifier: "ParamBinding",
});
const bindable = <A, I>(s: S.Schema<A, I>) => S.Union(s, ParamBinding);
/** `"$me"` is the viewing member. */
const MemberTarget = S.Union(S.Literal("$me"), Handle, ParamBinding).annotations({
  identifier: "MemberTarget",
});
const Slug = S.String.pipe(S.pattern(/^[a-z][a-z0-9]*(?:[-.][a-z0-9]+)*$/));
const PageSize = S.optional(S.Int.pipe(S.between(3, 100)));
const LinkGroup = S.optional(
  S.String.pipe(
    S.pattern(/^[a-z][a-z0-9-]{0,31}$/),
    S.annotations({
      description: "Widgets with the same link group exchange selections on the page bus (default 'page').",
    }),
  ),
);

export const WIDGET_SIZES = ["s", "m", "l", "xl", "full"] as const;
export const WidgetSize = S.Literal(...WIDGET_SIZES).annotations({ identifier: "WidgetSize" });
export type WidgetSize = typeof WidgetSize.Type;

/** Grid footprint of each size variant on the 12-column page grid (rows are 4.5rem). */
export const SIZE_GRID: Record<WidgetSize, { readonly w: number; readonly h: number }> = {
  s: { w: 3, h: 3 },
  m: { w: 4, h: 5 },
  l: { w: 6, h: 6 },
  xl: { w: 8, h: 8 },
  full: { w: 12, h: 10 },
};

/** Page bus topics: how widgets on one page interact without knowing each other. Payload is `{ id }` (or slug). */
export const BUS_TOPICS = [
  "thread.selected",
  "member.selected",
  "product.selected",
  "order.selected",
  "promotion.selected",
  "automation.selected",
  "run.selected",
  "content.selected",
  "segment.selected",
  "task.selected",
  "approval.selected",
  "badge.selected",
  "date.selected",
  "filter.changed",
] as const;
export type BusTopic = (typeof BUS_TOPICS)[number];

export const WIDGET_PACKAGES = ["A", "B", "C", "D"] as const;

export interface WidgetDef {
  readonly id: string;
  readonly domain: string;
  readonly title: string;
  readonly description: string;
  /** Work package that builds it (UI-MAP.md section 6). */
  readonly pkg: (typeof WIDGET_PACKAGES)[number];
  readonly sizes: ReadonlyArray<WidgetSize>;
  readonly default_size: WidgetSize;
  readonly config: S.Schema.AnyNoContext;
  /** Internal views the widget switches between itself (no page navigation needed). */
  readonly views: ReadonlyArray<string>;
  /** Registry actions it calls. */
  readonly actions: ReadonlyArray<string>;
  /** Domain event types it reacts to (plus `changes` on node kinds where noted in `nodes`). */
  readonly events: ReadonlyArray<DomainEventType>;
  readonly nodes?: ReadonlyArray<string>;
  readonly publishes: ReadonlyArray<BusTopic>;
  readonly subscribes: ReadonlyArray<BusTopic>;
  /** Permission needed to see the widget at all; without it the host renders the "not available" state. */
  readonly permission: string;
}

const w = (d: WidgetDef): WidgetDef => d;
const C = <F extends S.Struct.Fields>(fields: F) => S.Struct({ ...fields, link_group: LinkGroup });
const E = (...e: ReadonlyArray<DomainEventType>) => e;

