/**
 * Suite reporting sources (CONTRACT.md section 13). Decision: curated Postgres views exposed as `metadata` Sources,
 * read through the same path as `audit.changes` (the engine selects the view's rows up to `as_of` on the time column,
 * hands them to DuckDB as the relation `plinth_meta`, and the query compiler applies grants, row predicates and masks).
 * DuckDB's `postgres` extension is not used: it would need a second extension download, database credentials inside
 * the query engine and a second path around the compiler. Every view has a `region` column so regional row
 * predicates (`region = 'EMEA'`) compile on every source, and a `workspace_id` column the compiler filters on.
 * Private text (message bodies, review bodies, emails) is never in a view.
 */

const f = (name: string, type: string, nullable: boolean, description?: string): FieldDecl => ({
  name,
  type,
  nullable,
  ...(description !== undefined ? { description } : {}),
});

const ENUMS = {
  region: [...REGIONS],
  tier: [...TIERS],
  surface: [...AUDIT_SURFACES],
  txn_type: [...TXN_TYPES],
  account_kind: ["member", "system"],
  order_status: [...ORDER_STATUSES],
  thread_kind: ["direct", "group", "broadcast", "system"],
  notification_type: [...NOTIFICATION_TYPES],
  rarity: [...BADGE_RARITIES],
  promo_context: ["purchase", "earn"],
  effect_type: ["points_multiplier", "bonus_points", "store_discount", "free_item"],
  run_status: [...RUN_STATUSES],
  trigger_type: ["event", "schedule", "metric", "manual", "retry"],
  step_type: [...STEP_TYPES],
  content_type: ["page", "article", "announcement"],
  reaction: [...REACTIONS],
  task_status: [...TASK_STATUSES],
  task_priority: [...TASK_PRIORITIES],
  task_source: ["manual", "automation"],
  event_type: [...DOMAIN_EVENT_TYPES],
  member_status: ["active", "disabled"],
  department: [...DEPARTMENTS],
} as const;

const pick = (...names: ReadonlyArray<keyof typeof ENUMS>) =>
  Object.fromEntries(names.map((n) => [n, [...ENUMS[n]]])) as Record<string, string[]>;

const source = (
  slug: string,
  title: string,
  time_column: string,
  primary_key: ReadonlyArray<string>,
  enums: ReadonlyArray<keyof typeof ENUMS>,
  fields: ReadonlyArray<FieldDecl>,
): SourceBody => ({
  apiVersion: "plinth/v1",
  kind: "Source",
  metadata: { slug, title, labels: { "plinth.suite": "true" } },
  spec: {
    kind: "metadata",
    domain: "suite",
    time_column,
    primary_key: [...primary_key],
    enums: pick(...enums),
    fields: [...fields],
  },
});

